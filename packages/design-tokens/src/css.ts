import { colors, durations, fontFamily, layout, radius, textStyles, type SemanticColors, type ThemeName } from "./tokens.ts";

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

function themeVars(theme: ThemeName): string {
  const c: SemanticColors = colors[theme];
  const lines: string[] = [];
  for (const [k, v] of Object.entries(c)) {
    if (Array.isArray(v)) {
      lines.push(`  --tc-${kebab(k)}-from: ${v[0]};`, `  --tc-${kebab(k)}-to: ${v[1]};`);
    } else {
      lines.push(`  --tc-${kebab(k)}: ${v};`);
    }
  }
  lines.push(`  color-scheme: ${theme};`);
  return lines.join("\n");
}

/**
 * CSS custom properties for both themes plus @font-face rules.
 * Dark is the default; set data-theme="light" on <html> for the light theme.
 * `fontBase` is the URL prefix of the fonts/web directory relative to the stylesheet.
 */
export function buildTokensCss(fontBase = "../fonts/web"): string {
  const shared: string[] = [
    `  --tc-font-sans: ${fontFamily.web.sans};`,
    `  --tc-font-mono: ${fontFamily.web.mono};`,
    ...Object.entries(radius).map(([k, v]) => `  --tc-radius-${kebab(k)}: ${v}px;`),
    ...Object.entries(durations).map(([k, v]) => `  --tc-dur-${kebab(k)}: ${v}ms;`),
    `  --tc-ease-spring: linear(0, 0.009, 0.035 2.1%, 0.141, 0.281 6.7%, 0.723 12.9%, 0.938 16.7%, 1.017, 1.077, 1.121, 1.149 24.3%, 1.159, 1.163, 1.161, 1.154 29.9%, 1.129 32.8%, 1.051 39.6%, 1.017 43.1%, 0.991, 0.977 51%, 0.974 53.8%, 0.975 57.1%, 0.997 69.8%, 1.003 76.9%, 1);`,
    `  --tc-ease-out: cubic-bezier(0.2, 0.8, 0.2, 1);`,
    ...Object.entries(layout)
      .filter(([, v]) => typeof v === "number")
      .map(([k, v]) => `  --tc-${kebab(k)}: ${v}px;`),
  ];
  const textClasses = Object.entries(textStyles)
    .map(([name, t]) => {
      const family = t.web.family === "mono" ? "var(--tc-font-mono)" : "var(--tc-font-sans)";
      const upper = "uppercase" in t && t.uppercase ? "\n  text-transform: uppercase;" : "";
      return `.tc-${kebab(name)} {\n  font-family: ${family};\n  font-weight: ${t.web.weight};\n  font-stretch: ${t.web.stretch};\n  font-size: ${t.size}px;\n  line-height: ${t.lineHeight}px;\n  letter-spacing: ${t.letterSpacing}px;${upper}\n}`;
    })
    .join("\n\n");

  return `/* Generated by @thumbcade/design-tokens — do not edit by hand. */
@font-face {
  font-family: "Mona Sans";
  src: url("${fontBase}/MonaSansVF.woff2") format("woff2");
  font-weight: 200 900;
  font-stretch: 75% 125%;
  font-display: swap;
}
@font-face {
  font-family: "Departure Mono";
  src: url("${fontBase}/DepartureMono-Regular.woff2") format("woff2");
  font-weight: 400;
  font-display: swap;
}

:root {
${shared.join("\n")}
}

:root,
[data-theme="dark"] {
${themeVars("dark")}
}

[data-theme="light"] {
${themeVars("light")}
}

${textClasses}
`;
}

/** Tailwind v4 theme mapping onto the CSS variables (import after tokens.css). */
export function buildTailwindTheme(): string {
  const colorKeys = Object.keys(colors.dark).filter((k) => !Array.isArray(colors.dark[k as keyof SemanticColors]));
  return `/* Generated by @thumbcade/design-tokens — do not edit by hand. */
@theme inline {
${colorKeys.map((k) => `  --color-${kebab(k)}: var(--tc-${kebab(k)});`).join("\n")}
  --color-heat: #FF4A3D;
  --color-ink-0: #000000;
  --color-ink-1: #0D0D10;
  --color-ink-2: #17171C;
  --color-ink-3: #24242B;
  --color-paper: #F3F0E8;
  --font-sans: var(--tc-font-sans);
  --font-mono: var(--tc-font-mono);
${Object.entries(radius)
  .map(([k, v]) => `  --radius-${kebab(k)}: ${v}px;`)
  .join("\n")}
}
`;
}
