// Embeds the brand SVGs from @thumbcade/design-tokens as strings for react-native-svg's SvgXml.
// The logo is never redrawn: this copies the source files verbatim. Run: node scripts/gen-brand.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const brand = resolve(here, "../../../packages/design-tokens/brand");
const files = { mark: "mark.svg", wordmark: "wordmark.svg", lockup: "lockup.svg" };
let out = "// Generated by scripts/gen-brand.mjs from packages/design-tokens/brand. Do not edit.\n";
for (const [name, file] of Object.entries(files)) {
  out += `export const ${name}Svg = ${JSON.stringify(readFileSync(resolve(brand, file), "utf8"))};\n`;
}
writeFileSync(resolve(here, "../src/ui/brand.generated.ts"), out);
console.log("wrote src/ui/brand.generated.ts");
